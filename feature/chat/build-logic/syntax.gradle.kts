import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

buildscript {
    repositories {
        google()
        mavenCentral()
    }

    dependencies { classpath("org.jetbrains.kotlinx:kotlinx-serialization-json:1.13.0") }
}

@CacheableTask
abstract class GenerateSyntax : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sourceDirectory: DirectoryProperty

    @get:OutputDirectory abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val sources = sourceDirectory.get().asFile
        val settings = Json.parseToJsonElement(sources.resolve("syntax.json").readText()).jsonObject
        val aliases = settings.getValue("aliases").jsonObject
        val output = outputDirectory.get().asFile.resolve("syntax/highlight.js")
        output.parentFile.mkdirs()
        output.bufferedWriter().use { writer ->
            writer.appendLine(
                "// Generated by :feature:chat:generateSyntax from highlight.js ${settings.getValue("version").jsonPrimitive.content}. Do not edit.",
            )
            sources.resolve("upstream.js").reader().use { it.copyTo(writer) }
            for ((alias, language) in aliases) {
                writer.appendLine(
                    "hljs.registerAliases(${JsonPrimitive(alias)}, {languageName:${language}});",
                )
            }
            sources.resolve("tokens.js").reader().use { it.copyTo(writer) }
        }
    }
}

@DisableCachingByDefault(
    because = "Updates the vendored upstream syntax source on explicit request",
)
abstract class UpdateSyntax : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val settingsFile: RegularFileProperty

    @get:OutputFile abstract val upstreamFile: RegularFileProperty

    @TaskAction
    fun update() {
        val settings = Json.parseToJsonElement(settingsFile.get().asFile.readText()).jsonObject
        val version = settings.getValue("version").jsonPrimitive.content
        val paths =
            listOf("highlight.min.js") +
                settings.getValue("languages").jsonArray.map {
                    "languages/${it.jsonPrimitive.content}.min.js"
                }
        val staging = temporaryDir.resolve("upstream.js")
        staging.bufferedWriter().use { writer ->
            for (path in paths) {
                val connection =
                    URI(
                            "https://raw.githubusercontent.com/highlightjs/cdn-release/$version/build/$path",
                        )
                        .toURL()
                        .openConnection()
                connection.connectTimeout = 30_000
                connection.readTimeout = 30_000
                connection.getInputStream().bufferedReader().use { it.copyTo(writer) }
                writer.appendLine()
            }
        }
        val destination = upstreamFile.get().asFile
        destination.parentFile.mkdirs()
        Files.move(staging.toPath(), destination.toPath(), StandardCopyOption.REPLACE_EXISTING)
    }
}

val generateSyntax =
    tasks.register<GenerateSyntax>("generateSyntax") {
        group = "build"
        description = "Generate the syntax tokenizer from the vendored sources."
        sourceDirectory.set(layout.projectDirectory.dir("src/main/syntax"))
        outputDirectory.set(layout.buildDirectory.dir("generated/syntaxResources"))
    }

tasks.register<UpdateSyntax>("updateSyntax") {
    group = "build setup"
    description = "Download the highlight.js sources declared in syntax.json."
    settingsFile.set(layout.projectDirectory.file("src/main/syntax/syntax.json"))
    upstreamFile.set(layout.projectDirectory.file("src/main/syntax/upstream.js"))
}
